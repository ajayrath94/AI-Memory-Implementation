/**
 * The backend stores language_pref as a phrase the composer can put in a
 * sentence — "hinglish", "Punjabi, written in Gurmukhi script, with English
 * words where natural". That is right for the prompt and useless as a key, so
 * it is matched back to a Lang here rather than stored twice.
 */
export function langFromPref(pref?: string | null): Lang {
  const p = (pref || '').toLowerCase()
  if (p.includes('punjab'))  return 'punjabi'
  if (p.includes('gujarat')) return 'gujarati'
  if (p.includes('marathi')) return 'marathi'
  if (p.includes('bengal'))  return 'bengali'
  if (p.includes('tamil'))   return 'tamil'
  if (p.includes('telugu'))  return 'telugu'
  if (p.includes('hinglish')) return 'hinglish'
  if (p.includes('hindi'))   return 'hindi'
  if (p.includes('english')) return 'english'
  return 'hinglish'          // what every existing profile says
}
